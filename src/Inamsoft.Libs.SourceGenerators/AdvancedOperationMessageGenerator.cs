    private static void GenerateContextType(StringBuilder builder, MemberModel m)
    {
        var typeName = $"{m.Name}Context";

        builder.AppendLine($"    public sealed record {typeName}(");
        builder.AppendLine(string.Join(",\n", m.Placeholders.Select(p =>
            p switch
            {
                "fileCount" => "        int FileCount",
                _ => $"        string {UpperFirst(p)}"
            })));
        builder.AppendLine("    );");
        builder.AppendLine();
    }

    private static void GenerateFormatterMethods(StringBuilder builder, MemberModel m)
    {
        var typeName = $"{m.Name}Context";

        builder.AppendLine($"    public static string {m.Name}({typeName} ctx)");
        builder.AppendLine("    {");
        builder.AppendLine($"        var template = GetTemplate(FileOperationType.{m.Name});");

        if (m.Placeholders.Length == 0)
        {
            builder.AppendLine("        return template;");
        }
        else
        {
            builder.Append("        return template");
            foreach (var p in m.Placeholders)
            {
                var prop = p == "fileCount" ? "FileCount" : UpperFirst(p);
                builder.Append($".Replace(\"{{{p}}}\", ctx.{prop}.ToString())");
            }
            builder.AppendLine(";");
        }

        builder.AppendLine("    }");
        builder.AppendLine();

        // Step-aware message
        builder.AppendLine($"    public static string {m.Name}(OperationStep step, {typeName} ctx)");
        builder.AppendLine("    {");
        builder.AppendLine("        var stepText = step switch");
        builder.AppendLine("        {");
        builder.AppendLine("            OperationStep.Begin => \"Begin\",");
        builder.AppendLine("            OperationStep.Finished => \"Finished\",");
        builder.AppendLine("            OperationStep.Skipped => \"Skipped\",");
        builder.AppendLine("            OperationStep.Retrying => \"Retrying\",");
        builder.AppendLine("            OperationStep.Failed => \"Failed\",");
        builder.AppendLine("            _ => step.ToString()");
        builder.AppendLine("        };");
        builder.AppendLine($"        return stepText + \" \" + {m.Name}(ctx);");
        builder.AppendLine("    }");
        builder.AppendLine();
    }

    private static void GenerateSpectreFormatterMethods(StringBuilder builder, MemberModel member)
    {
        var typeName = $"{member.Name}Context";

        builder.AppendLine($"    public static string {member.Name}Spectre({typeName} ctx)");
        builder.AppendLine("    {");
        builder.AppendLine($"        var template = GetTemplate(FileOperationType.{member.Name});");

        if (member.Placeholders.Length == 0)
        {
            builder.AppendLine("        return template;");
        }
        else
        {
            builder.Append("        return template");
            foreach (var p in member.Placeholders)
            {
                var prop = p == "fileCount" ? "FileCount" : UpperFirst(p);
                var color = p switch
                {
                    "fileName" => "yellow",
                    "source" => "blue",
                    "destination" => "blue",
                    "fileCount" => "green",
                    _ => "white"
                };
                builder.Append($".Replace(\"{{{p}}}\", $\"[{color}]{{ctx.{prop}}}[/]\")");
            }
            builder.AppendLine(";");
        }

        builder.AppendLine("    }");
        builder.AppendLine();

        builder.AppendLine($"    public static string {member.Name}Spectre(OperationStep step, {typeName} ctx)");
        builder.AppendLine("    {");
        builder.AppendLine("        var stepText = step switch");
        builder.AppendLine("        {");
        builder.AppendLine("            OperationStep.Begin => \"Begin\",");
        builder.AppendLine("            OperationStep.Finished => \"Finished\",");
        builder.AppendLine("            OperationStep.Skipped => \"Skipped\",");
        builder.AppendLine("            OperationStep.Retrying => \"Retrying\",");
        builder.AppendLine("            OperationStep.Failed => \"Failed\",");
        builder.AppendLine("            _ => step.ToString()");
        builder.AppendLine("        };");
        builder.AppendLine($"        return stepText + \" \" + {member.Name}Spectre(ctx);");
        builder.AppendLine("    }");
        builder.AppendLine();
    }

    private static void GenerateProgressHelper(StringBuilder builder, MemberModel member)
    {
        var typeName = $"{member.Name}Context";

        builder.AppendLine($"    public static void {member.Name}ProgressTask(ProgressTask task, OperationStep step, {typeName} ctx)");
        builder.AppendLine("    {");
        builder.AppendLine($"        var message = {member.Name}Spectre(step, ctx);");
        builder.AppendLine("        task.Description = message;");
        builder.AppendLine("    }");
        builder.AppendLine();
    }

    private static string UpperFirst(string s)
    {
        if (string.IsNullOrEmpty(s))
            return s;

        if (s.Length == 1)
            return s.ToUpperInvariant();

        return char.ToUpperInvariant(s[0]) + s.Substring(1);
    }

    private sealed record EnumModel(string Namespace, string Name, ImmutableArray<MemberModel> Members);
    private sealed record MemberModel(
        string Name,
        string Template,
        ImmutableArray<string> Placeholders,
        ImmutableArray<string> InvalidPlaceholders,
        ImmutableArray<string> Required,
        ImmutableArray<string> Optional);
}
