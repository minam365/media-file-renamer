    private static readonly ImmutableHashSet<string> AllowedPlaceholders =
        ImmutableHashSet.Create("fileName", "fileCount", "source", "destination");

    // Constant definitions for GenerateDictionaryAttribute
    private const string AttributesNamespace = "Inamsoft.Libs.SourceGenerators.Attributes";

    private const string OperationTemplateAttribClassName = "OperationTemplateAttribute";
    private const string OperationTemplateAttribFullName = AttributesNamespace + "." + OperationTemplateAttribClassName;

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        // Find all enum declarations
        var enumDeclarations = context.SyntaxProvider
            .CreateSyntaxProvider(
                predicate: static (node, _) => node is EnumDeclarationSyntax,
                transform: static (ctx, _) => (EnumDeclarationSyntax)ctx.Node)
            .Where(static e => e is not null);

        // Combine enum syntax with semantic model
        var enumSymbols = context.CompilationProvider.Combine(enumDeclarations.Collect())
            .SelectMany(static (pair, _) =>
            {
                var (compilation, enums) = pair;
                var list = ImmutableArray.CreateBuilder<INamedTypeSymbol>();

                foreach (var e in enums)
                {
                    var symbol = compilation.GetSemanticModel(e.SyntaxTree).GetDeclaredSymbol(e) as INamedTypeSymbol;
                    if (symbol is not null)
                        list.Add(symbol);
                }

                return list.ToImmutable();
            });

        // Generate output
        context.RegisterSourceOutput(enumSymbols, static (ctx, enumSymbol) =>
        {
            var source = GenerateForEnum(enumSymbol);
            if (source is not null)
            {
                ctx.AddSource($"{enumSymbol.Name}_OperationTemplates.g.cs",
                    SourceText.From(source, Encoding.UTF8));
            }
        });
    }

    private static string? GenerateForEnum(INamedTypeSymbol enumSymbol)
    {
        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated />");
        builder.AppendLine($"// EnumName: {GetSafeTypeName(enumSymbol)}");
        
        var ns = GetOutputNamespace(enumSymbol);

        var markList = new List<(string Name, string Template)>();

        foreach (var member in enumSymbol.GetMembers())
        {
            if (member is not IFieldSymbol field || field.ConstantValue is null)
                continue;

            foreach (var attr in field.GetAttributes())
            {
                if (attr.AttributeClass?.ToDisplayString() != OperationTemplateAttribFullName) 
                    continue;
                
                var template = attr.ConstructorArguments[0].Value?.ToString();
                if (template is not null)
                    markList.Add((field.Name, template));
            }
        }

        if (markList.Count == 0)
            return null;

        if (ns is not null)
        {
            builder.AppendLine($"namespace {ns};");
            builder.AppendLine();
        }

        builder.AppendLine($"public static class OperationTemplates_{enumSymbol.Name}");
        builder.AppendLine("{");

        // Constants
        foreach (var (name, template) in markList)
        {
            var escaped = template.Replace("\"", "\"\"");
            builder.AppendLine($"    public const string {name} = \"{escaped}\";");
        }

        builder.AppendLine();
        var enumTypeName = GetSafeTypeName(enumSymbol);

        builder.AppendLine("    /// <summary>");
        builder.AppendLine("    /// Gets the template string for the specified operation type.");
        builder.AppendLine("    /// </summary>");
        builder.AppendLine($"    public static string GetTemplate({enumTypeName} op) => op switch");
        builder.AppendLine("    {");
        foreach (var (name, template) in markList)
        {
            var escaped = template.Replace("\"", "\\\"");
            //builder.AppendLine($"        FileOperationType.{name} => \"{escaped}\",");
            builder.AppendLine($"        {enumTypeName}.{name} => {name},");
        }
        builder.AppendLine("        _ => throw new ArgumentOutOfRangeException(nameof(op))");
        builder.AppendLine("    };");
        builder.AppendLine();

        // Structured logging template (no step prefix, just the template)
        builder.AppendLine("    public static string GetLogTemplate(FileOperationType op) => GetTemplate(op);");
        builder.AppendLine();

        // Metadata for analyzer & logging
        builder.AppendLine("    public static class OperationMessagesMetadata");
        builder.AppendLine("    {");
        builder.AppendLine("        public static readonly System.Collections.Generic.Dictionary<FileOperationType, string[]> Placeholders =");
        builder.AppendLine("            new System.Collections.Generic.Dictionary<FileOperationType, string[]>");
        builder.AppendLine("            {");
        foreach (var (name, template) in markList)
        {
            var placeholders = ExtractPlaceholders(template).ToList();
            if (placeholders.Count > 0)
            {
                var list = string.Join(", ", placeholders.Select(p => $"\"{p}\""));
                builder.AppendLine($"                [{enumTypeName}.{name}] = new[] {{ {list} }},");
            }
            else
            {
                builder.AppendLine($"                [{enumTypeName}.{name}] = [],");
            }
        }
        builder.AppendLine("            };");
        builder.AppendLine("    }");
        builder.AppendLine();

        builder.AppendLine("}");

        return builder.ToString();
    }



